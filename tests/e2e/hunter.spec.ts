import { test, expect } from "@playwright/test";
test("保存済み市場を走査し、URLフィルター・詳細・モバイル・デジャヴ導線を維持", async ({ page }) => {
  const started = performance.now();
  await page.goto("/bottom/hunter?asOf=2026-10-09");
  await expect(page.getByRole("heading", { name: "底打ちハンター", exact: true })).toBeVisible();
  console.log(`hunter initial heading ms=${(performance.now()-started).toFixed(1)}`);
  await page.getByText("取得・走査ジョブを明示的に開始", { exact: true }).click();
  await page.getByRole("button", { name: "ジョブを開始", exact: true }).click();
  await expect(page.locator(".hunter-desktop tbody tr")).toHaveCount(4, { timeout: 120000 });
  await expect(page.getByLabel("カバレッジ")).toContainText("対象 4銘柄");
  await expect(page.getByRole("heading", { name: "データ品質" })).toBeVisible();
  await expect(page.getByLabel("カバレッジ")).toContainText("取得対象期間");
  const min = page.getByLabel("スコア下限", { exact: true });
  await min.fill("100"); await expect(page).toHaveURL(/minScore=100/);
  await page.goBack(); await expect(min).toHaveValue("");
  await expect(page.locator(".hunter-desktop tbody tr")).toHaveCount(4);
  const chartStarted = performance.now();
  await page.locator(".hunter-desktop tbody tr").filter({ hasText: "架空モビリティ" }).getByRole("button", { name: "底打ち詳細を見る" }).click();
  await expect(page.getByRole("heading", { name: "架空モビリティ 底打ち詳細" })).toBeVisible();
  await expect(page.getByRole("img", { name: "80営業日のローソク足・5日平均・20日平均・出来高" })).toBeVisible();
  console.log(`hunter detail-to-chart ms=${(performance.now()-chartStarted).toFixed(1)}`);
  const apiStarted = performance.now();
  const response = await page.request.get("/api/bottom/hunter/rankings?pageSize=25");
  expect(response.ok()).toBe(true);
  console.log(`hunter rankings API ms=${(performance.now()-apiStarted).toFixed(1)}`);
  await expect(page.getByRole("heading", { name: "デジャヴ未来シナリオ", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".hunter-mobile > article")).toHaveCount(4);
  await expect(page.locator(".hunter-desktop tbody tr")).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/hunter-mobile.png", fullPage: true });
  await page.locator(".hunter-mobile > article").filter({ hasText: "架空モビリティ" }).getByRole("link", { name: "デジャヴ相場を見る" }).click();
  await expect(page).toHaveURL(/hunterJobId=/);
  await expect(page.getByRole("heading", { name: "デジャヴ未来シナリオ", exact: true })).toBeVisible();
});

test("狭い画面のページングとURL復元、初期集計抑止、エラーと空結果の区別", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  let summaries = 0;
  page.on("request", req => { if (req.url().includes("/bottom/hunter/evaluations")) summaries++; });
  await page.goto("/bottom/hunter?asOf=2026-10-09&pageSize=1");
  await page.getByText("取得・走査ジョブを明示的に開始", { exact: true }).click();
  await page.getByRole("button", { name: "ジョブを開始", exact: true }).click();
  await expect(page.getByRole("heading", { name: "底打ちハンター", exact: true })).toBeVisible();
  await expect(page.locator(".hunter-mobile > article")).toHaveCount(1);
  expect(summaries).toBe(0);
  const firstTitle = await page.locator(".hunter-mobile > article h3").first().innerText();
  await page.getByRole("button", { name: "次のページ", exact: true }).click();
  await expect(page).toHaveURL(/page=2/);
  await expect(page.locator(".hunter-mobile > article h3").first()).not.toHaveText(firstTitle);
  await expect(page.locator(".hunter-mobile > article")).toHaveCount(1);
  await page.evaluate(() => window.scrollTo(0, 400));
  await expect.poll(() => page.evaluate(() => Object.keys(sessionStorage).some(k => k.startsWith("hunter-scroll:") && new URLSearchParams(k.slice("hunter-scroll:".length)).get("page") === "2" && Number(sessionStorage.getItem(k)) > 300 && Number(sessionStorage.getItem(k)) < 500))).toBe(true);
  await page.reload();
  await expect(page.locator(".hunter-mobile > article")).toHaveCount(1);
  await expect(page).toHaveURL(/page=2/);
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(300);
  await expect(page.locator(".hunter-mobile > article")).toHaveCount(1);
  await page.getByRole("button", { name: "成績集計を表示" }).click();
  await expect.poll(() => summaries).toBe(1);
  await expect(page.getByText("評価対象の予測記録がありません。")).toBeVisible();
  await page.route("**/api/bottom/hunter/rankings?**", route => route.fulfill({ status: 500, contentType: "application/json", body: JSON.stringify({ error: "fixture ranking error" }) }));
  await page.getByLabel("スコア下限", { exact: true }).fill("99");
  await expect(page.getByRole("alert").filter({ hasText: "fixture ranking error" })).toBeVisible({ timeout: 30000 });
  await expect(page.getByText("この条件の走査済み結果はありません。基準日を指定してジョブを開始してください。")).toHaveCount(0);
});
